#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { copyPackage, inventory, extractRanges, checkLinks, sourceStatus } from '../codex/skills/2e_handoff-refinement/scripts/package-tools.mjs';
const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'refinement-package-'));
try {
  const source = path.join(temp, 'source'), copy = path.join(temp, 'copy'); fs.mkdirSync(source);
  const bytes = Buffer.from('# Requirements\r\n- AC-12a: Import rows.\r\n  - Preserve nested detail.  \r\n\r\n- AC-16a: Confirm result.\r\n');
  fs.writeFileSync(path.join(source, 'prd.md'), bytes);
  fs.writeFileSync(path.join(source, 'screen.png'), Buffer.from([137, 80, 78, 71, 0, 255]));
  const original = copyPackage(source, copy);
  assert.deepEqual(inventory(copy), original);
  assert.deepEqual(fs.readFileSync(path.join(copy, 'prd.md')), bytes);
  assert.throws(() => copyPackage(source, copy), /new/);
  assert.throws(() => copyPackage(source, path.join(source, 'nested')), /inside source/);
  const selections = [{ path: 'prd.md', sourceId: 'AC-12a', startLine: 2, endLine: 4 }, { path: 'prd.md', sourceId: 'AC-16a', startLine: 5, endLine: 5 }];
  const requirements = extractRanges(copy, 'product@v1', selections);
  assert.equal(requirements[0].text, '- AC-12a: Import rows.\r\n  - Preserve nested detail.  \r\n\r');
  assert.equal(requirements.length, 2, 'whole-deliverable questions can reference every returned ID');
  assert.throws(() => extractRanges(copy, 'product@v1', [...selections, selections[0]]), /Duplicate/);
  assert.throws(() => extractRanges(copy, 'product@v1', [{ ...selections[0], sourceId: 'AC-12' }]), /lacks identity/);
  assert.throws(() => extractRanges(copy, 'product@v1', [{ ...selections[0], path: '../outside' }]), /Unsafe/);
  const round = path.join(temp, 'round'); fs.mkdirSync(round);
  fs.writeFileSync(path.join(round, 'questions.md'), '[Evidence](evidence.md)\n![Screen](screen.png)\n[Source][source]\n[source]: evidence.md\n');
  fs.writeFileSync(path.join(round, 'evidence.md'), requirements.map(r => r.text).join('\n'));
  fs.copyFileSync(path.join(source, 'screen.png'), path.join(round, 'screen.png'));
  const detached = path.join(temp, 'detached'); copyPackage(round, detached);
  fs.rmSync(round, { recursive: true });
  assert.equal(checkLinks(detached).checked.length, 3);
  fs.writeFileSync(path.join(detached, 'missing.md'), '[Source][missing]');
  assert.throws(() => checkLinks(detached), /Undefined reference/);
  fs.rmSync(path.join(detached, 'missing.md'));
  fs.appendFileSync(path.join(detached, 'questions.md'), '\n[Receiver](../copy/prd.md)');
  assert.throws(() => checkLinks(detached), /Unsafe/);
  fs.symlinkSync(source, path.join(copy, 'outside')); assert.throws(() => inventory(copy), /Symlink/);
  fs.rmSync(path.join(copy, 'outside'));
  const git = (...args) => execFileSync('git', args, { cwd: source, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
  git('init', '-q'); git('config', 'user.email', 'test@example.invalid'); git('config', 'user.name', 'Test');
  git('add', '.'); git('commit', '-m', 'Packaged six-step concept');
  const pin = git('rev-parse', 'HEAD'); assert.equal(sourceStatus(source, pin).moved, false);
  fs.writeFileSync(path.join(source, 'concept.md'), 'Revision 7: five steps');
  git('add', '.'); git('commit', '-m', 'New source decision during review');
  const changed = sourceStatus(source, pin);
  assert.equal(changed.moved, true); assert.match(changed.changedPaths, /concept.md/);
  assert.deepEqual(inventory(copy), original, 'live source never changes frozen inventory');
  console.log('refinement package: binary/CRLF preservation, ranges, identities, detached links and moving source passed');
} finally { fs.rmSync(temp, { recursive: true, force: true }); }
